    fn boucle_sans_fin_arretee() {
        let d = tmp("loop");
        std::fs::write(
            d.join("hyprland.lua"),
            "hl.env('A','1')\nwhile true do end\n",
        )
        .unwrap();
        let s = read_file(&d.join("hyprland.lua"));
        assert!(s.error.is_some());
        assert_eq!(s.calls_of("env").count(), 1);
    }


//! Lecture de `hyprland.lua` par évaluation (MLG-137) : ce que le fichier
//! définit vraiment — options de `hl.config`, courbes, animations, variables
//! d'environnement, règles, raccourcis, démarrages — avec la ligne d'origine.
//!
//! Le fichier est exécuté dans un Lua isolé où chaque fonction `hl.*` est un
//! bouchon qui **enregistre** son appel : les boucles (`for … do
//! hl.window_rule(…) end`) et les tables de données sont donc comprises,
//! là où une lecture du texte les manquerait. `os.getenv` reste réel (les
//! chemins calculés le sont comme dans Hyprland) ; `io`, `os.execute`,
//! `loadfile`… sont retirés, et un plafond d'instructions arrête une boucle
//! sans fin. Les `require` locaux sont suivis, sauf les fichiers générés par
//! hyprdesk (ils décrivent hyprdesk, pas l'utilisateur).
//!
//! En plus de l'évaluation, le texte de chaque `hl.config({ … })` est relu
//! pour situer chaque clé (lignes de début et de fin de sa valeur) : c'est ce
//! qui permet de commenter exactement une option adoptée par hyprdesk.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use mlua::{HookTriggers, Lua, Table, Value, VmState};
use serde_json::Value as Json;

/// Plafond d'instructions de l'évaluation (une config fait quelques milliers).
const BUDGET: u32 = 5_000_000;

/// Un appel `hl.<func>(…)` relevé à l'évaluation.
#[derive(Debug, Clone, PartialEq)]
pub struct Call {
    /// Nom de la fonction (`config`, `env`, `window_rule`, `curve`…).
    pub func: String,
    pub args: Vec<Json>,
    pub file: PathBuf,
    /// Ligne de l'appel (1-based).
    pub line: usize,
    /// Appel fait dans un rappel `hl.on("<événement>", …)`.
    pub context: Option<String>,
    /// Instruction calculée (environnement, `io`, `hl.get_config`) : sa
    /// valeur dépend de la machine, elle ne se reprend pas telle quelle.
    pub computed: bool,
    /// Lignes [début, fin] (1-based) de l'instruction de premier niveau qui
    /// la contient (une boucle entière pour un appel dans une boucle).
    pub stmt: (usize, usize),
}

/// Une option définie par `hl.config`, à plat (`decoration.blur.enabled`).
#[derive(Debug, Clone, PartialEq)]
pub struct OptionDef {
    pub value: Json,
    pub file: PathBuf,
    /// Lignes [début, fin] (1-based) de la clé et de sa valeur dans le
    /// fichier ; celles de l'appel si la clé n'a pas été retrouvée.
    pub lines: (usize, usize),
    pub computed: bool,
}

/// Ce que définit la configuration de Hyprland.
#[derive(Debug, Default, Clone)]
pub struct Source {
    pub calls: Vec<Call>,
    /// Dernière définition de chaque option (la dernière gagne, comme dans
    /// Hyprland).
    pub options: BTreeMap<String, OptionDef>,
    /// Évaluation interrompue (erreur Lua, plafond atteint) : ce qui précède
    /// reste relevé.
    pub error: Option<String>,
}

impl Source {
    /// Appels d'une fonction donnée.
    pub fn calls_of<'a>(&'a self, func: &'a str) -> impl Iterator<Item = &'a Call> + 'a {
        self.calls.iter().filter(move |c| c.func == func)
    }
}

/// Fichier généré par hyprdesk (en-tête « Généré par hyprdesk »).
pub fn generated(content: &str) -> bool {
    let first = content.lines().next().unwrap_or("").trim_start();
    first.starts_with("-- Généré par hyprdesk") || first.starts_with("-- Generated by hyprdesk")
}

/// Lit `hyprland.lua` (à côté de la config de hyprdesk).
pub fn read(config_path: &Path) -> Source {
    let dir = config_path.parent().unwrap_or(Path::new("."));
    read_file(&dir.join("hyprland.lua"))
}

/// Lit un fichier de config Hyprland et ses `require` locaux.
pub fn read_file(main: &Path) -> Source {
    let dir = main.parent().unwrap_or(Path::new(".")).to_path_buf();
    let src = match std::fs::read_to_string(main) {
        Ok(s) => s,
        Err(e) => {
            return Source {
                error: Some(e.to_string()),
                ..Default::default()
            };
        }
    };
    let mut out = evaluate(&dir, main, &src);
    locate(&mut out);
    out
}

/// Prélude Lua : `hl` enregistreur, `require` local, bibliothèques risquées
/// retirées.
const PRELUDE: &str = r#"
__calls = {}
__ctx = nil
local function record(name, level, ...)
    local src, line = __where(level)
    table.insert(__calls, { name = name, args = table.pack(...),
        src = src or "", line = line or 0, ctx = __ctx })
end
local function handle()
    return setmetatable({}, { __index = function() return function() end end })
end
-- Bouchon appelable et indexable : `hl.window_rule(…)`, mais aussi
-- `hl.dsp.window.close()` ou `hl.plugin.x.y(…)`.
local function node(name, records)
    return setmetatable({}, {
        __call = function(_, ...)
            if records then
                record(name, 3, ...)
                return handle()
            end
            return { __dsp = name, args = table.pack(...) }
        end,
        __index = function(t, k)
            local n = node(name == "" and k or (name .. "." .. k), records)
            rawset(t, k, n)
            return n
        end,
    })
end
hl = setmetatable({ dsp = node("", false) }, { __index = function(t, k)
    local n = node(k, true)
    rawset(t, k, n)
    return n
end })
hl.get_config = function() return nil end
hl.on = function(ev, fn)
    record("on", 3, ev)
    local prev = __ctx
    __ctx = "on:" .. tostring(ev)
    if type(fn) == "function" then pcall(fn) end
    __ctx = prev
end
require = function(name)
    local src, path = __load(name)
    if not src then return true end
    local chunk = load(src, "@" .. path)
    if chunk then return chunk() end
    return true
end
io = nil
loadfile = nil
dofile = nil
if os then
    os.execute = nil; os.remove = nil; os.rename = nil; os.exit = nil; os.tmpname = nil
end
if package then package.loadlib = nil end
"#;

fn evaluate(dir: &Path, main: &Path, src: &str) -> Source {
    let lua = Lua::new();
    let mut out = Source::default();
    let budget = std::sync::Arc::new(std::sync::atomic::AtomicU32::new(0));
    let b = budget.clone();
    let _ = lua.set_hook(
        HookTriggers::new().every_nth_instruction(1000),
        move |_, _| {
            if b.fetch_add(1000, std::sync::atomic::Ordering::Relaxed) > BUDGET {
                Err(mlua::Error::runtime("plafond d'instructions atteint"))
            } else {
                Ok(VmState::Continue)
            }
        },
    );
    // Fichier et ligne de l'appelant : la bibliothèque `debug` n'est pas
    // chargée en mode sûr ; la pile est lue côté Rust. Niveau 0 : cette
    // fonction, 1 : `record`, 2 : le bouchon `hl.x`, 3 : la config.
    let whence = lua.create_function(|lua, level: usize| {
        Ok(lua
            .inspect_stack(level, |d| {
                (d.source().source.map(|s| s.to_string()), d.current_line())
            })
            .unwrap_or((None, None)))
    });
    let dir_owned = dir.to_path_buf();
    let loader = lua.create_function(move |_, name: String| {
        let rel = name.replace('.', "/");
        let p = dir_owned.join(format!("{rel}.lua"));
        match std::fs::read_to_string(&p) {
            Ok(s) if !generated(&s) => Ok((Some(s), Some(p.display().to_string()))),
            _ => Ok((None, None)),
        }
    });
    let run = || -> mlua::Result<()> {
        lua.globals().set("__load", loader?)?;
        lua.globals().set("__where", whence?)?;
        lua.load(PRELUDE).set_name("=prelude").exec()?;
        lua.load(src)
            .set_name(format!("@{}", main.display()))
            .exec()
    };
    if let Err(e) = run() {
        out.error = Some(e.to_string());
    }
    if let Ok(calls) = lua.globals().get::<Table>("__calls") {
        for c in calls.sequence_values::<Table>().flatten() {
            let name: String = c.get("name").unwrap_or_default();
            let line: usize = c.get::<i64>("line").unwrap_or(0).max(0) as usize;
            let source: String = c.get("src").unwrap_or_default();
            let file = PathBuf::from(source.strip_prefix('@').unwrap_or(&source));
            let ctx: Option<String> = c.get("ctx").ok();
            let args: Vec<Json> = c
                .get::<Table>("args")
                .map(|t| {
                    let n: i64 = t.get("n").unwrap_or(0);
                    (1..=n)
                        .map(|i| to_json(&t.get::<Value>(i).unwrap_or(Value::Nil), 0))
                        .collect()
                })
                .unwrap_or_default();
            out.calls.push(Call {
                func: name,
                args,
                file,
                line,
                context: ctx,
                computed: false,
                stmt: (line, line),
            });
        }
    }
    out
}

/// Valeur Lua → JSON (tables-séquences en tableaux, fonctions en marqueur).
fn to_json(v: &Value, depth: usize) -> Json {
    if depth > 16 {
        return Json::Null;
    }
    match v {
        Value::Nil => Json::Null,
        Value::Boolean(b) => Json::Bool(*b),
        Value::Integer(i) => Json::from(*i),
        Value::Number(n) => serde_json::Number::from_f64(*n)
            .map(Json::Number)
            .unwrap_or(Json::Null),
        Value::String(s) => Json::String(s.to_string_lossy().to_string()),
        Value::Table(t) => {
            let len = t.raw_len();
            let mut pairs: Vec<(Value, Value)> = t.clone().pairs().flatten().collect();
            let is_seq = len > 0
                && pairs.len() == len
                && pairs.iter().all(|(k, _)| matches!(k, Value::Integer(_)));
            if is_seq {
                pairs.sort_by_key(|(k, _)| match k {
                    Value::Integer(i) => *i,
                    _ => 0,
                });
                Json::Array(pairs.iter().map(|(_, v)| to_json(v, depth + 1)).collect())
            } else {
                let mut m = serde_json::Map::new();
                for (k, v) in pairs {
                    let key = match k {
                        Value::String(s) => s.to_string_lossy().to_string(),
                        Value::Integer(i) => i.to_string(),
                        _ => continue,
                    };
                    if key == "n" && matches!(v, Value::Integer(_)) && t.raw_len() == 0 {
                        // `table.pack` : compteur, pas une donnée.
                        continue;
                    }
                    m.insert(key, to_json(&v, depth + 1));
                }
                Json::Object(m)
            }
        }
        Value::Function(_) => Json::String("<fonction>".into()),
        _ => Json::Null,
    }
}

/// Valeur d'option « feuille » : pas une sous-section de `hl.config`
/// (dégradé `{ colors, angle }`, côtés `{ top, … }`, liste).
fn is_leaf_object(m: &serde_json::Map<String, Json>) -> bool {
    let keys: Vec<&str> = m.keys().map(String::as_str).collect();
    !keys.is_empty()
        && (keys.iter().all(|k| matches!(*k, "colors" | "angle"))
            || keys
                .iter()
                .all(|k| matches!(*k, "top" | "right" | "bottom" | "left")))
}

/// Aplatit une table `hl.config` en chemins pointés.
pub fn flatten(v: &Json, prefix: &str, out: &mut Vec<(String, Json)>) {
    match v {
        Json::Object(m) if !is_leaf_object(m) => {
            for (k, val) in m {
                let p = if prefix.is_empty() {
                    k.clone()
                } else {
                    format!("{prefix}.{k}")
                };
                flatten(val, &p, out);
            }
        }
        _ if !prefix.is_empty() => out.push((prefix.to_string(), v.clone())),
        _ => {}
    }
}

/// Situe instructions et clés dans le texte, et repère le calculé.
fn locate(out: &mut Source) {
    let mut texts: BTreeMap<PathBuf, Vec<String>> = BTreeMap::new();
    let mut spans_of: BTreeMap<PathBuf, Vec<(usize, usize, String)>> = BTreeMap::new();
    for c in &out.calls {
        if texts.contains_key(&c.file) {
            continue;
        }
        let Ok(src) = std::fs::read_to_string(&c.file) else {
            continue;
        };
        let lines: Vec<String> = src.lines().map(str::to_string).collect();
        let items = crate::binds_file::items(&src);
        // Texte de chaque instruction, avec celui des locales qu'elle emploie
        // (la table de données d'une boucle).
        let mut spans = Vec::new();
        for it in &items {
            let mut text = lines[it.start..it.end].join("\n");
            for u in &it.uses {
                if let Some(def) = items.iter().find(|d| d.defines.as_deref() == Some(u)) {
                    text.push('\n');
                    text.push_str(&lines[def.start..def.end].join("\n"));
                }
            }
            spans.push((it.start + 1, it.end, text));
        }
        texts.insert(c.file.clone(), lines);
        spans_of.insert(c.file.clone(), spans);
    }
    for c in &mut out.calls {
        if let Some((s, e, text)) = spans_of
            .get(&c.file)
            .and_then(|v| v.iter().find(|(s, e, _)| *s <= c.line && c.line <= *e))
        {
            c.stmt = (*s, *e);
            c.computed = computed(text);
        }
    }
    for c in out.calls.iter().filter(|c| c.func == "config") {
        let Some(arg) = c.args.first() else { continue };
        let mut flat = Vec::new();
        flatten(arg, "", &mut flat);
        let keys = texts
            .get(&c.file)
            .map(|lines| key_spans(lines, c.stmt.0, c.stmt.1))
            .unwrap_or_default();
        for (path, value) in flat {
            let span = keys.get(&path).copied();
            let computed = match (span, texts.get(&c.file)) {
                (Some((a, b)), Some(lines)) => computed(&lines[a - 1..b].join("\n")),
                _ => c.computed,
            };
            out.options.insert(
                path,
                OptionDef {
                    value,
                    file: c.file.clone(),
                    lines: span.unwrap_or(c.stmt),
                    computed,
                },
            );
        }
    }
}

/// Le texte dépend de la machine (environnement, fichiers, état de Hyprland).
fn computed(text: &str) -> bool {
    [
        "os.getenv",
        "os.date",
        "os.time",
        "io.",
        "hl.get_config",
        "require(",
    ]
    .iter()
    .any(|m| text.contains(m))
}

#[derive(Debug, Clone, PartialEq)]
enum Tok {
    Ident(String),
    Str(String),
    Sym(char),
    Other,
}

/// Jetons d'un morceau de source Lua, avec leur ligne (1-based) ; chaînes
/// et commentaires (longs compris) reconnus.
fn tokens(lines: &[String], from: usize, to: usize) -> Vec<(Tok, usize)> {
    let mut out = Vec::new();
    let mut long_comment = false;
    for (n, line) in lines.iter().enumerate().take(to).skip(from - 1) {
        let ln = n + 1;
        let ch: Vec<char> = line.chars().collect();
        let mut i = 0;
        while i < ch.len() {
            if long_comment {
                if ch[i] == ']' && ch.get(i + 1) == Some(&']') {
                    long_comment = false;
                    i += 2;
                } else {
                    i += 1;
                }
                continue;
            }
            let c = ch[i];
            if c == '-' && ch.get(i + 1) == Some(&'-') {
                if ch.get(i + 2) == Some(&'[') && ch.get(i + 3) == Some(&'[') {
                    long_comment = true;
                    i += 4;
                    continue;
                }
                break;
            }
            if c == '"' || c == '\'' {
                let mut s = String::new();
                i += 1;
                while i < ch.len() && ch[i] != c {
                    if ch[i] == '\\' {
                        i += 1;
                    }
                    if i < ch.len() {
                        s.push(ch[i]);
                    }
                    i += 1;
                }
                i += 1;
                out.push((Tok::Str(s), ln));
                continue;
            }
            if c.is_alphabetic() || c == '_' {
                let mut s = String::new();
                while i < ch.len() && (ch[i].is_alphanumeric() || ch[i] == '_') {
                    s.push(ch[i]);
                    i += 1;
                }
                out.push((Tok::Ident(s), ln));
                continue;
            }
            if c.is_whitespace() {
                i += 1;
                continue;
            }
            if "{}[]=,;().".contains(c) {
                out.push((Tok::Sym(c), ln));
            } else {
                out.push((Tok::Other, ln));
            }
            i += 1;
        }
    }
    out
}

/// Lignes [début, fin] de chaque clé des tables d'un `hl.config({ … })`
/// situé lignes [from, to] : chemin pointé → lignes.
pub fn key_spans(lines: &[String], from: usize, to: usize) -> BTreeMap<String, (usize, usize)> {
    let toks = tokens(lines, from, to.min(lines.len()));
    let mut out = BTreeMap::new();
    // Premier `{` après `config (`.
    let Some(open) = toks.iter().position(|(t, _)| *t == Tok::Sym('{')) else {
        return out;
    };
    table(&toks, open, "", &mut out);
    out
}

/// Parcourt la table qui s'ouvre en `i` ; renvoie l'indice après sa `}`.
fn table(
    toks: &[(Tok, usize)],
    mut i: usize,
    prefix: &str,
    out: &mut BTreeMap<String, (usize, usize)>,
) -> usize {
    i += 1;
    while i < toks.len() {
        match &toks[i].0 {
            Tok::Sym('}') => return i + 1,
            Tok::Sym(',') | Tok::Sym(';') => {
                i += 1;
                continue;
            }
            _ => {}
        }
        // Clé : `nom =` ou `["nom"] =`.
        let (key, start_line, after) = match (&toks[i].0, toks.get(i + 1).map(|t| &t.0)) {
            (Tok::Ident(k), Some(Tok::Sym('='))) => (Some(k.clone()), toks[i].1, i + 2),
            (Tok::Sym('['), _) => match (toks.get(i + 1), toks.get(i + 2), toks.get(i + 3)) {
                (Some((Tok::Str(k), _)), Some((Tok::Sym(']'), _)), Some((Tok::Sym('='), _))) => {
                    (Some(k.clone()), toks[i].1, i + 4)
                }
                _ => (None, toks[i].1, i),
            },
            _ => (None, toks[i].1, i),
        };
        let path = key.map(|k| {
            if prefix.is_empty() {
                k
            } else {
                format!("{prefix}.{k}")
            }
        });
        // Valeur : table (récursion) ou jetons jusqu'au `,`/`}` de ce niveau.
        let mut j = after;
        if toks.get(j).map(|t| &t.0) == Some(&Tok::Sym('{')) {
            let sub = path.clone().unwrap_or_default();
            j = table(toks, j, &sub, out);
        } else {
            let mut depth = 0i32;
            while j < toks.len() {
                match toks[j].0 {
                    Tok::Sym('{') | Tok::Sym('(') | Tok::Sym('[') => depth += 1,
                    Tok::Sym('}') | Tok::Sym(')') | Tok::Sym(']') if depth > 0 => depth -= 1,
                    Tok::Sym('}') | Tok::Sym(',') | Tok::Sym(';') if depth == 0 => break,
                    _ => {}
                }
                j += 1;
            }
        }
        let end_line = toks
            .get(j.saturating_sub(1))
            .map_or(start_line, |t| t.1)
            .max(start_line);
        if let Some(p) = path {
            out.insert(p, (start_line, end_line));
        }
        i = j.max(i + 1);
    }
    i
}


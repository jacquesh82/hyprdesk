//! Historique de la configuration (MLG-138) : avant chaque écriture d'un
//! fichier de configuration, hyprdesk en garde une copie datée pendant
//! 30 jours, avec retour arrière.
//!
//! Les instantanés vont dans `$XDG_STATE_HOME/hyprdesk/history/` (sinon
//! `~/.local/state/hyprdesk/history/`), jamais sous `~/.config/hypr/` : la
//! veille de la config y verrait un changement et rechargerait tout. Un
//! instantané est un dossier `<AAAAMMJJ-HHMMSS>-<motif>` qui contient la copie
//! des fichiers suivis (chemins relatifs au dossier de `hyprdesk.lua`) et
//! `manifest.json` (horodatage, motif, empreinte et taille de chaque fichier).
//!
//! Règles :
//! - pas d'instantané si rien n'a changé depuis le dernier ;
//! - un seul par série : même motif à moins de 60 s du dernier, l'état
//!   d'avant la série suffit ;
//! - élagage à 30 jours, le plus récent toujours gardé ;
//! - un instantané garde l'état *d'avant* une écriture de hyprdesk, ou l'état
//!   *d'après* une modification à la main (motif `main`, vue par la veille
//!   du démon).
//!
//! `written.json`, à côté des instantanés, retient l'empreinte de ce que
//! hyprdesk a écrit en dernier dans chaque fichier, quel que soit le
//! processus (démon, ligne de commande) : la veille du démon distingue ainsi
//! ses propres écritures d'une modification à la main.

use std::cell::Cell;
use std::collections::{BTreeMap, BTreeSet};
use std::io::{self, Read, Write};
use std::path::{Component, Path, PathBuf};
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
use std::sync::{Mutex, OnceLock};

use chrono::{DateTime, Local, NaiveDate, NaiveDateTime, TimeZone};
use serde::{Deserialize, Serialize};

/// Fichiers suivis, relatifs au dossier de `hyprdesk.lua` (en plus de
/// `hyprdesk.lua` lui-même et de tout `*.lua` de premier niveau généré par
/// hyprdesk). Ceux qui n'existent pas sont simplement absents de l'instantané.
pub const TRACKED: &[&str] = &[
    "hyprland.lua",
    "binds.lua",
    "autostart.lua",
    "monitors.lua",
    "inputs.lua",
    "appearance.lua",
    "animations.lua",
    "layouts.lua",
    "rules.lua",
    "env.lua",
    "system.lua",
    "hyprdesk/settings.lua",
];

/// Durée de conservation des instantanés.
pub const KEEP_DAYS: i64 = 30;
/// Regroupement : même motif à moins de ce délai du dernier instantané.
pub const GROUP_SECS: i64 = 60;

/// En-têtes des fichiers que hyprdesk génère (et réécrit en entier).
const GENERATED: &[&str] = &["-- Généré par hyprdesk", "-- Generated by hyprdesk"];

const MANIFEST: &str = "manifest.json";
const WRITTEN: &str = "written.json";

/// Un fichier dans un instantané : chemin relatif, empreinte, taille.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FileEntry {
    pub file: String,
    pub hash: String,
    pub size: u64,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct Manifest {
    version: u32,
    /// Horodatage en millisecondes depuis l'époque Unix.
    unix_ms: i64,
    /// Même moment, lisible (RFC 3339, heure locale).
    time: String,
    reason: String,
    files: Vec<FileEntry>,
}

/// Un instantané de l'historique.
#[derive(Debug, Clone, PartialEq)]
pub struct Snapshot {
    /// Nom du dossier : `<AAAAMMJJ-HHMMSS>-<motif>`.
    pub id: String,
    pub dir: PathBuf,
    pub unix_ms: i64,
    pub reason: String,
    pub files: Vec<FileEntry>,
}

impl Snapshot {
    pub fn time(&self) -> DateTime<Local> {
        Local
            .timestamp_millis_opt(self.unix_ms)
            .single()
            .unwrap_or_else(Local::now)
    }
}

/// Un instantané et les fichiers changés juste après lui (par rapport à
/// l'instantané suivant, ou à l'état actuel pour le plus récent).
#[derive(Debug, Clone, PartialEq)]
pub struct Entry {
    pub snap: Snapshot,
    pub changed: Vec<String>,
}

/// Nature de l'écart d'un fichier entre un instantané et l'état actuel.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Change {
    /// Présent maintenant, absent de l'instantané.
    Added,
    /// Présent dans l'instantané, absent maintenant.
    Removed,
    Modified,
}

impl Change {
    pub fn label(self) -> &'static str {
        match self {
            Change::Added => crate::i18n::tr("ajouté depuis"),
            Change::Removed => crate::i18n::tr("retiré depuis"),
            Change::Modified => crate::i18n::tr("modifié depuis"),
        }
    }
}

/// Écart d'un fichier : diff unifié de l'instantané (−) vers l'état actuel (+).
#[derive(Debug, Clone, PartialEq)]
pub struct FileDiff {
    pub file: String,
    pub change: Change,
    pub patch: String,
}

/// Ce que ferait (ou a fait) un retour arrière.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct Plan {
    /// Fichiers réécrits avec le contenu de l'instantané.
    pub restore: Vec<String>,
    /// Fichiers générés par hyprdesk absents de l'instantané : supprimés.
    pub remove: Vec<String>,
}

/// Résultat d'un retour arrière.
#[derive(Debug, Clone, PartialEq)]
pub struct Restored {
    pub id: String,
    /// Instantané de l'état d'avant le retour arrière.
    pub safety: String,
    pub plan: Plan,
}

/// Hyprland, vu du retour arrière : erreurs de configuration et rechargement.
/// Injectable pour les tests.
pub trait Hypr {
    fn errors(&self) -> Vec<String>;
    fn reload(&self);
}

/// Hyprland de la session ; sans `HYPRLAND_INSTANCE_SIGNATURE`, rien.
pub struct Live;

impl Live {
    fn present() -> bool {
        std::env::var_os("HYPRLAND_INSTANCE_SIGNATURE").is_some_and(|s| !s.is_empty())
    }
}

impl Hypr for Live {
    fn errors(&self) -> Vec<String> {
        if Self::present() {
            crate::hyprcheck::config_errors()
        } else {
            Vec::new()
        }
    }

    fn reload(&self) {
        if Self::present() {
            let _ = std::process::Command::new("hyprctl").arg("reload").output();
            std::thread::sleep(std::time::Duration::from_millis(300));
        }
    }
}


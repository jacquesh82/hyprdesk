pub fn snapshot(config_path: &Path, reason: &str) -> io::Result<Option<Snapshot>> {
    Store::user().snapshot_at(config_path, reason, Local::now())
}

/// Instantané de l'état actuel à rétablir ensuite (`Store::mark_at`).
pub fn mark(config_path: &Path, reason: &str) -> io::Result<Option<String>> {
    Store::user().mark_at(config_path, reason, Local::now())
}

#[allow(dead_code)]
pub fn list() -> Vec<Snapshot> {
    Store::user().list()
}

pub fn prune(now: DateTime<Local>) -> usize {
    Store::user().prune_at(now)
}

pub fn entries(config_path: &Path) -> Vec<Entry> {
    Store::user().entries(config_path)
}

/// Écart entre l'instantané `id` et l'état actuel.
pub fn diff(config_path: &Path, id: &str) -> Result<(Snapshot, Vec<FileDiff>), String> {
    let s = Store::user();
    let snap = s.resolve(id)?;
    let d = s.diff_of(config_path, &snap);
    Ok((snap, d))
}

/// Ce que ferait le retour à `id`.
pub fn plan(config_path: &Path, id: &str) -> Result<(Snapshot, Plan), String> {
    let s = Store::user();
    let snap = s.resolve(id)?;
    let p = s.plan(config_path, &snap);
    Ok((snap, p))
}


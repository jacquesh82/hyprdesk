    struct Fake {
        after: Vec<String>,
        reloads: RefCell<usize>,
    }

    impl Hypr for Fake {
        fn errors(&self) -> Vec<String> {
            if *self.reloads.borrow() % 2 == 1 {
                self.after.clone()
            } else {
                Vec::new()
            }
        }
        fn reload(&self) {
            *self.reloads.borrow_mut() += 1;
        }
    }

    #[test]
    fn retour_arriere_restaure_les_fichiers() {
        let (cfg, s) = setup("retour");
        write(&cfg, "hyprdesk/settings.lua", "hd.config({ a = 1 })\n");
        let old = s
            .snapshot_at(&cfg, "reglages", t("2026-11-16 10:00:00"))
            .unwrap()
            .unwrap();
        write(&cfg, "hyprland.lua", "changé\n");
        write(&cfg, "hyprdesk/settings.lua", "hd.config({ a = 2 })\n");
        write(&cfg, "inputs.lua", "-- Généré par hyprdesk (Réglages)\n");
        write(&cfg, "perso.lua", "-- à moi\n");
        let p = s.plan(&cfg, &old);
        assert_eq!(p.restore, ["hyprdesk/settings.lua", "hyprland.lua"]);
        assert_eq!(p.remove, ["inputs.lua"]);
        let fake = Fake {
            after: Vec::new(),
            reloads: RefCell::new(0),
        };
        let r = s
            .rollback_with(&cfg, &old.id[..8], &fake, t("2026-11-16 11:00:00"))
            .unwrap();
        assert_eq!(r.id, old.id);
        assert_eq!(r.plan, p);
        assert_eq!(*fake.reloads.borrow(), 1);
        let dir = config_dir(&cfg);
        assert_eq!(
            std::fs::read_to_string(dir.join("hyprland.lua")).unwrap(),
            "a\nb\nc\n"
        );
        assert_eq!(
            std::fs::read_to_string(dir.join("hyprdesk/settings.lua")).unwrap(),
            "hd.config({ a = 1 })\n"
        );
        assert!(!dir.join("inputs.lua").exists());
        assert!(dir.join("perso.lua").exists());
        // L'état d'avant le retour est gardé, et le retour est retenu
        // comme écrit par hyprdesk : la veille n'y voit pas de main.
        let safety = s.resolve(&r.safety).unwrap();
        assert_eq!(safety.reason, "retour-arriere");
        assert!(!s.foreign(&cfg));
        // Retour au retour : tout revient.
        s.rollback_with(&cfg, &r.safety, &fake, t("2026-11-16 11:00:30"))
            .unwrap();
        assert_eq!(
            std::fs::read_to_string(dir.join("hyprland.lua")).unwrap(),
            "changé\n"
        );
        assert!(dir.join("inputs.lua").exists());
    }


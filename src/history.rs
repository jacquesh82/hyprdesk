// Empreintes, fichiers suivis

/// Empreinte stable (FNV-1a 64 bits) : de quoi voir qu'un fichier a changé.
fn fingerprint(bytes: &[u8]) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in bytes {
        h ^= u64::from(*b);
        h = h.wrapping_mul(0x0100_0000_01b3);
    }
    format!("fnv1a64:{h:016x}")
}

fn config_dir(config_path: &Path) -> &Path {
    config_path
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or(Path::new("."))
}

/// Fichier généré par hyprdesk (d'après son en-tête).
fn generated(p: &Path) -> bool {
    let mut head = [0u8; 64];
    let Ok(mut f) = std::fs::File::open(p) else {
        return false;
    };
    let mut n = 0;
    while n < head.len() {
        match f.read(&mut head[n..]) {
            Ok(0) | Err(_) => break,
            Ok(k) => n += k,
        }
    }
    GENERATED
        .iter()
        .any(|g| head[..n].starts_with(g.as_bytes()))
}

/// Chemin relatif sûr (pas d'absolu ni de `..`) : un manifeste trafiqué ne
/// doit pas faire écrire hors du dossier de config.
fn safe_rel(rel: &str) -> bool {
    !rel.is_empty()
        && Path::new(rel)
            .components()
            .all(|c| matches!(c, Component::Normal(_)))
}

/// Chemin relatif de `p` s'il fait partie des fichiers suivis.
fn tracked_rel(config_path: &Path, p: &Path) -> Option<String> {
    let rel = p.strip_prefix(config_dir(config_path)).ok()?;
    let rel = rel.to_str()?.to_string();
    let own = config_path.file_name().and_then(|n| n.to_str());
    let top_lua = !rel.contains('/') && rel.ends_with(".lua");
    (TRACKED.contains(&rel.as_str()) || own == Some(rel.as_str()) || (top_lua && generated(p)))
        .then_some(rel)
}

/// Changement possible d'un fichier suivi, sans lire le fichier (veille).
pub fn may_track(config_path: &Path, p: &Path) -> bool {
    p.strip_prefix(config_dir(config_path))
        .ok()
        .and_then(Path::to_str)
        .is_some_and(|rel| (!rel.contains('/') && rel.ends_with(".lua")) || TRACKED.contains(&rel))
}

/// Fichiers suivis existants, relatifs au dossier de config, triés.
pub fn tracked(config_path: &Path) -> Vec<String> {
    let dir = config_dir(config_path);
    let mut set: BTreeSet<String> = TRACKED.iter().map(|s| s.to_string()).collect();
    if let Some(n) = config_path.file_name().and_then(|n| n.to_str()) {
        set.insert(n.to_string());
    }
    for e in std::fs::read_dir(dir).into_iter().flatten().flatten() {
        let p = e.path();
        if let Some(name) = p.file_name().and_then(|n| n.to_str())
            && name.ends_with(".lua")
            && p.is_file()
            && generated(&p)
        {
            set.insert(name.to_string());
        }
    }
    set.into_iter().filter(|r| dir.join(r).is_file()).collect()
}

/// Fichiers suivis et leur contenu.
fn current(config_path: &Path) -> Vec<(FileEntry, Vec<u8>)> {
    let dir = config_dir(config_path);
    tracked(config_path)
        .into_iter()
        .filter_map(|rel| {
            let bytes = std::fs::read(dir.join(&rel)).ok()?;
            Some((
                FileEntry {
                    hash: fingerprint(&bytes),
                    size: bytes.len() as u64,
                    file: rel,
                },
                bytes,
            ))
        })
        .collect()
}

fn slug(reason: &str) -> String {
    let s: String = reason
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect();
    let s = s
        .split('-')
        .filter(|p| !p.is_empty())
        .collect::<Vec<_>>()
        .join("-");
    if s.is_empty() { "instantane".into() } else { s }
}

/// Écriture atomique (temporaire + renommage) ; un lien symbolique est
/// suivi : c'est le fichier pointé qui est remplacé, le lien reste.
fn atomic_write(path: &Path, bytes: &[u8]) -> io::Result<()> {
    static N: AtomicU64 = AtomicU64::new(0);
    let real = if path.is_symlink() {
        std::fs::canonicalize(path)?
    } else {
        path.to_path_buf()
    };
    let parent = real.parent().unwrap_or(Path::new("."));
    std::fs::create_dir_all(parent)?;
    let temp = parent.join(format!(
        ".hyprdesk-history-{}-{}.tmp",
        std::process::id(),
        N.fetch_add(1, Ordering::Relaxed)
    ));
    let result = (|| {
        let mut f = std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&temp)?;
        f.write_all(bytes)?;
        f.sync_all()?;
        std::fs::rename(&temp, &real)
    })();
    if result.is_err() {
        let _ = std::fs::remove_file(&temp);
    }
    result
}


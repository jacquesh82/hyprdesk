/// Config de ce processus ; tant qu'elle n'est pas posée (tests), les
/// branchements ne font rien.
static CONFIG: OnceLock<PathBuf> = OnceLock::new();
/// Démon lancé : la veille prend les instantanés `main`.
static DAEMON: AtomicBool = AtomicBool::new(false);

thread_local! {
    /// Motif des écritures implicites (`storage::write`) de ce fil.
    static REASON: Cell<Option<&'static str>> = const { Cell::new(None) };
}

/// Pose la config de ce processus (au lancement de `hyprdesk`).
pub fn init(config_path: &Path) {
    let _ = CONFIG.set(config_path.to_path_buf());
}

fn config() -> Option<&'static Path> {
    CONFIG.get().map(PathBuf::as_path)
}

/// Motif des écritures implicites de ce fil tant que la garde vit.
pub struct ReasonGuard(Option<&'static str>);

impl Drop for ReasonGuard {
    fn drop(&mut self) {
        REASON.with(|r| r.set(self.0));
    }
}

pub fn reason(r: &'static str) -> ReasonGuard {
    ReasonGuard(REASON.with(|c| c.replace(Some(r))))
}

fn implicit_reason(rel: &str) -> &'static str {
    REASON.with(Cell::get).unwrap_or(match rel {
        "autostart.lua" => "demarrage",
        "binds.lua" => "raccourcis",
        _ => "reglages",
    })
}

fn log(r: io::Result<Option<Snapshot>>) {
    match r {
        Ok(Some(s)) => tracing::debug!("historique : {}", s.id),
        Ok(None) => {}
        Err(e) => tracing::warn!("{}", crate::tr!("historique de la config : {e}", e = e)),
    }
}

/// Avant une écriture implicite (`storage::write`) : instantané si `path`
/// est un fichier suivi.
pub fn before_write(path: &Path) {
    let Some(cfg) = config() else { return };
    let Some(rel) = tracked_rel(cfg, path) else {
        return;
    };
    log(Store::user().snapshot_at(cfg, implicit_reason(&rel), Local::now()));
}

/// Avant une série d'écritures de motif connu.
pub fn before(config_path: &Path, reason: &str) {
    if config().is_some() {
        log(snapshot(config_path, reason));
    }
}

/// Après une écriture (ou suppression) de hyprdesk : retenue, pour que la
/// veille ne la prenne pas pour une modification à la main.
pub fn note(path: &Path) {
    let Some(cfg) = config() else { return };
    let Some(rel) = tracked_rel(cfg, path).or_else(|| {
        // Fichier supprimé : plus d'en-tête à lire.
        let rel = path.strip_prefix(config_dir(cfg)).ok()?.to_str()?;
        TRACKED.contains(&rel).then(|| rel.to_string())
    }) else {
        return;
    };
    Store::user().record(&rel, std::fs::read(path).ok().as_deref());
}

/// `fs::write` d'un fichier suivi : instantané avant, retenue après.
/// (Pas de renommage : un hyprland.lua en lien symbolique le reste.)
pub fn write_file(path: &Path, contents: impl AsRef<[u8]>, reason: &str) -> io::Result<()> {
    if let Some(cfg) = config()
        && tracked_rel(cfg, path).is_some()
    {
        log(Store::user().snapshot_at(cfg, reason, Local::now()));
    }
    std::fs::write(path, contents)?;
    note(path);
    Ok(())
}

/// Lancement du démon : élagage, instantané des modifications faites à la
/// main pendant son absence, puis veille.
pub fn start_daemon() {
    DAEMON.store(true, Ordering::Relaxed);
    let Some(cfg) = config() else { return };
    let now = Local::now();
    prune(now);
    log(Store::user().on_change_at(cfg, now));
}

/// Veille du démon : un fichier suivi a changé (bloquant : hors du fil de
/// l'interface).
pub fn on_change() {
    if !DAEMON.load(Ordering::Relaxed) {
        return;
    }
    if let Some(cfg) = config() {
        log(Store::user().on_change_at(cfg, Local::now()));
    }
}


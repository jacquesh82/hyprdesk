    #[test]
    fn veille_distingue_les_ecritures_de_hyprdesk() {
        let (cfg, s) = setup("veille");
        assert!(
            s.on_change_at(&cfg, t("2026-11-16 10:00:00"))
                .unwrap()
                .is_some()
        );
        // Écriture de hyprdesk : retenue, pas de « main ».
        write(&cfg, "hyprland.lua", "par hyprdesk\n");
        s.record("hyprland.lua", Some(b"par hyprdesk\n"));
        assert!(
            s.on_change_at(&cfg, t("2026-11-16 10:05:00"))
                .unwrap()
                .is_none()
        );
        // Modification à la main : instantané « main ».
        write(&cfg, "hyprland.lua", "à la main\n");
        let m = s
            .on_change_at(&cfg, t("2026-11-16 10:10:00"))
            .unwrap()
            .unwrap();
        assert_eq!(m.reason, "main");
        // Suppression par hyprdesk, retenue.
        write(&cfg, "inputs.lua", "-- Généré par hyprdesk\n");
        s.snapshot_at(&cfg, "reglages", t("2026-11-16 10:20:00"))
            .unwrap()
            .unwrap();
        std::fs::remove_file(config_dir(&cfg).join("inputs.lua")).unwrap();
        s.record("inputs.lua", None);
        assert!(!s.foreign(&cfg));
    }


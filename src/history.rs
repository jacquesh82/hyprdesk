// Diff unifié (LCS par lignes)

enum Op<'a> {
    Same(&'a str),
    Del(&'a str),
    Add(&'a str),
}

fn ops<'a>(a: &[&'a str], b: &[&'a str]) -> Vec<Op<'a>> {
    let pre = a.iter().zip(b).take_while(|(x, y)| x == y).count();
    let suf = a[pre..]
        .iter()
        .rev()
        .zip(b[pre..].iter().rev())
        .take_while(|(x, y)| x == y)
        .count();
    let (ma, mb) = (&a[pre..a.len() - suf], &b[pre..b.len() - suf]);
    let mut out: Vec<Op> = a[..pre].iter().map(|l| Op::Same(l)).collect();
    let (n, m) = (ma.len(), mb.len());
    if n * m > 4_000_000 {
        // Trop gros pour la table : tout retiré, tout ajouté.
        out.extend(ma.iter().map(|l| Op::Del(l)));
        out.extend(mb.iter().map(|l| Op::Add(l)));
    } else {
        // lcs[i][j] : plus longue sous-suite commune de ma[i..] et mb[j..].
        let w = m + 1;
        let mut lcs = vec![0u32; (n + 1) * w];
        for i in (0..n).rev() {
            for j in (0..m).rev() {
                lcs[i * w + j] = if ma[i] == mb[j] {
                    lcs[(i + 1) * w + j + 1] + 1
                } else {
                    lcs[(i + 1) * w + j].max(lcs[i * w + j + 1])
                };
            }
        }
        let (mut i, mut j) = (0, 0);
        while i < n || j < m {
            if i < n && j < m && ma[i] == mb[j] {
                out.push(Op::Same(ma[i]));
                i += 1;
                j += 1;
            } else if i < n && (j == m || lcs[(i + 1) * w + j] >= lcs[i * w + j + 1]) {
                out.push(Op::Del(ma[i]));
                i += 1;
            } else {
                out.push(Op::Add(mb[j]));
                j += 1;
            }
        }
    }
    out.extend(a[a.len() - suf..].iter().map(|l| Op::Same(l)));
    out
}

/// Diff unifié de `a` vers `b`, contexte de 3 lignes ; vide s'ils sont égaux.
pub fn unified(a: &str, b: &str, name_a: &str, name_b: &str) -> String {
    const CTX: usize = 3;
    let la: Vec<&str> = a.lines().collect();
    let lb: Vec<&str> = b.lines().collect();
    let ops = ops(&la, &lb);
    let changed: Vec<usize> = ops
        .iter()
        .enumerate()
        .filter(|(_, o)| !matches!(o, Op::Same(_)))
        .map(|(i, _)| i)
        .collect();
    if changed.is_empty() {
        return String::new();
    }
    // Numéros de ligne (0-based) avant chaque opération.
    let mut pos = Vec::with_capacity(ops.len() + 1);
    let (mut x, mut y) = (0usize, 0usize);
    for o in &ops {
        pos.push((x, y));
        match o {
            Op::Same(_) => {
                x += 1;
                y += 1;
            }
            Op::Del(_) => x += 1,
            Op::Add(_) => y += 1,
        }
    }
    pos.push((x, y));
    let mut out = format!("--- {name_a}\n+++ {name_b}\n");
    let mut k = 0;
    while k < changed.len() {
        let first = changed[k];
        let mut last = first;
        while k + 1 < changed.len() && changed[k + 1] - last <= 2 * CTX + 1 {
            k += 1;
            last = changed[k];
        }
        k += 1;
        let start = first.saturating_sub(CTX);
        let end = (last + CTX + 1).min(ops.len());
        let (os, ns) = pos[start];
        let (oe, ne) = pos[end];
        let (oc, nc) = (oe - os, ne - ns);
        let os1 = if oc == 0 { os } else { os + 1 };
        let ns1 = if nc == 0 { ns } else { ns + 1 };
        out += &format!("@@ -{os1},{oc} +{ns1},{nc} @@\n");
        for o in &ops[start..end] {
            match o {
                Op::Same(l) => out += &format!(" {l}\n"),
                Op::Del(l) => out += &format!("-{l}\n"),
                Op::Add(l) => out += &format!("+{l}\n"),
            }
        }
    }
    out
}

